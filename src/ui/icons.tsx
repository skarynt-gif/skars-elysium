import type { ReactElement } from 'react';

/**
 * Hand-drawn 9×9 pixel icons, rendered as crisp SVG squares so they stay
 * sharp at any size. '#' = filled pixel.
 */
const ICONS = {
  play: ['.#.......', '.##......', '.###.....', '.####....', '.#####...', '.####....', '.###.....', '.##......', '.#.......'],
  pause: ['.........', '.##...##.', '.##...##.', '.##...##.', '.##...##.', '.##...##.', '.##...##.', '.##...##.', '.........'],
  next: ['.........', '#...#...#', '##..##..#', '###.###.#', '#########', '###.###.#', '##..##..#', '#...#...#', '.........'],
  prev: ['.........', '#...#...#', '#..##..##', '#.###.###', '#########', '#.###.###', '#..##..##', '#...#...#', '.........'],
  volume: ['....#....', '...##..#.', '####.#..#', '####..#.#', '####..#.#', '####..#.#', '####.#..#', '...##..#.', '....#....'],
  mute: ['....#....', '...##....', '####.....', '####.#..#', '####..##.', '####..##.', '####.#..#', '...##....', '....#....'],
  up: ['.........', '.........', '....#....', '...###...', '..##.##..', '.##...##.', '##.....##', '.........', '.........'],
  down: ['.........', '.........', '##.....##', '.##...##.', '..##.##..', '...###...', '....#....', '.........', '.........'],
  close: ['.........', '.##...##.', '..##.##..', '...###...', '....#....', '...###...', '..##.##..', '.##...##.', '.........'],
  menu: ['.........', '#########', '#########', '.........', '#########', '#########', '.........', '#########', '#########'],
  note: ['....#####', '....#####', '....#...#', '....#...#', '....#...#', '.####.###', '#####.###', '#####.###', '.###.....'],
  lyre: ['#.......#', '##.....##', '.#.....#.', '.#.###.#.', '.##.#.##.', '..##.##..', '..#.#.#..', '..#####..', '...###...'],
} as const;

export type IconName = keyof typeof ICONS;

export function PixelIcon({ name, size = 18, title }: { name: IconName; size?: number; title?: string }) {
  const rows = ICONS[name];
  const rects: ReactElement[] = [];
  rows.forEach((row, y) => {
    for (let x = 0; x < row.length; x++) {
      if (row[x] === '#') rects.push(<rect key={`${x},${y}`} x={x} y={y} width={1} height={1} />);
    }
  });
  return (
    <svg
      className="pixel-icon"
      width={size}
      height={size}
      viewBox="0 0 9 9"
      shapeRendering="crispEdges"
      fill="currentColor"
      aria-hidden={title ? undefined : true}
      role={title ? 'img' : undefined}
    >
      {title && <title>{title}</title>}
      {rects}
    </svg>
  );
}
